def read_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def set_cell_text(cell, text: str, *, bold: bool = False, size: int = 8) -> None:
    cell.text = ""
    para = cell.paragraphs[0]
    para.paragraph_format.space_after = Pt(0)
    run = para.add_run(str(text))
    run.bold = bold
    run.font.size = Pt(size)
    cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER


def shade_cell(cell, fill: str) -> None:
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = tc_pr.find(qn("w:shd"))
    if shd is None:
        shd = OxmlElement("w:shd")
        tc_pr.append(shd)
    shd.set(qn("w:fill"), fill)


def set_cell_margins(cell, top: int = 80, start: int = 80, bottom: int = 80, end: int = 80) -> None:
    tc = cell._tc
    tc_pr = tc.get_or_add_tcPr()
    tc_mar = tc_pr.first_child_found_in("w:tcMar")
    if tc_mar is None:
        tc_mar = OxmlElement("w:tcMar")
        tc_pr.append(tc_mar)
    for m, v in {"top": top, "start": start, "bottom": bottom, "end": end}.items():
        node = tc_mar.find(qn(f"w:{m}"))
        if node is None:
            node = OxmlElement(f"w:{m}")
            tc_mar.append(node)
        node.set(qn("w:w"), str(v))
        node.set(qn("w:type"), "dxa")


def usable_width_inches(doc: Document) -> float:
    section = doc.sections[0]
    width_emu = section.page_width - section.left_margin - section.right_margin
    return max(3.6, min(6.1, width_emu / 914400))


def insert_paragraph(doc: Document, ref_para, text: str = "", style: str | None = None):
    para = doc.add_paragraph(text, style=style)
    ref_para._p.addprevious(para._p)
    return para


def insert_table(doc: Document, ref_para, caption: str, headers: list[str], rows: list[list[Any]]) -> None:
    caption_para = insert_paragraph(doc, ref_para, caption, "Caption")
    caption_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    table = doc.add_table(rows=1, cols=len(headers))
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.style = "Table Grid"
    for i, header in enumerate(headers):
        set_cell_text(table.rows[0].cells[i], header, bold=True, size=7)
        shade_cell(table.rows[0].cells[i], "E8EEF7")
        set_cell_margins(table.rows[0].cells[i])
    for row in rows:
        cells = table.add_row().cells
        for i, value in enumerate(row):
            set_cell_text(cells[i], value, size=7)
            if len(table.rows) % 2 == 0:
                shade_cell(cells[i], "F8FAFC")
            set_cell_margins(cells[i])
    ref_para._p.addprevious(table._tbl)
    spacer = insert_paragraph(doc, ref_para, "")
    spacer.paragraph_format.space_after = Pt(4)


def insert_image(doc: Document, ref_para, image_path: Path, caption: str, width_inches: float) -> None:
    para = doc.add_paragraph()
    para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = para.add_run()
    run.add_picture(str(image_path), width=Inches(width_inches))
    ref_para._p.addprevious(para._p)
    cap = insert_paragraph(doc, ref_para, caption, "Caption")
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER


def insert_code_block(doc: Document, ref_para, title: str, code: str) -> None:
    caption = insert_paragraph(doc, ref_para, title, "Caption")
    caption.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for line in code.strip().splitlines():
        para = insert_paragraph(doc, ref_para, line)
        run = para.runs[0] if para.runs else para.add_run(line)
        run.font.name = "Courier New"
        run._element.rPr.rFonts.set(qn("w:ascii"), "Courier New")
        run._element.rPr.rFonts.set(qn("w:hAnsi"), "Courier New")
        run.font.size = Pt(7)
        para.paragraph_format.space_after = Pt(0)
        para.paragraph_format.left_indent = Inches(0.15)


